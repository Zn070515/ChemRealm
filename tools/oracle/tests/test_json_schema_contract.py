"""The emitted JSON Schema artifacts are CONSUMED, not merely produced.

`PLAN-0001` M1's stop condition reads, verbatim:

    the JSON Schema artifact is emitted and consumed by at least one Python
    test that validates a fixture against it. That last item is what proves
    ADR-0001's "one source of truth" claim rather than asserting it.

Until this module existed, the artifacts were emitted and drift-checked —
`pnpm verify:schema-artifacts` fails if the working copy differs — but nothing
in Python read them. A drift check proves the file matches zod. It does not
prove the file is *usable*, and it cannot notice that the emitted form is
weaker than the runtime: `QuantitySchema` enforced its unit table with
`.refine()`, which zod's JSON Schema emission does not encode, so the emitted
`quantity.schema.json` accepted `{"value": 1, "unit": "furlong"}` while
`parseQuantity` rejected it. The boundary is where that class of defect lives,
which is why this test lives here and not in `contracts.test.ts`.

WHAT THIS PROVES, AND WHY EACH PART IS NEEDED
---------------------------------------------
1. Every artifact loads as draft-2020-12. Catches a malformed emission.
2. A valid fixture is ACCEPTED. Without this, a vacuously over-strict artifact
   would pass every test below.
3. An invalid fixture is REJECTED. Without this, a schema of `{}` would pass
   (1) and (2) and prove nothing.
4. Specific runtime rules survive the language boundary: an unknown unit, a
   wrong dimension, and an unknown key are refused by the ARTIFACT the same way
   the runtime refuses them.

The fixtures below are hand-written rather than generated from the TypeScript,
deliberately. A fixture generated by the same code that emits the schema would
agree with it by construction and could never detect a wrong schema.
"""

