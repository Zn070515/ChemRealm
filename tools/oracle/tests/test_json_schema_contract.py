def load_artifact(name: str) -> dict:
    path = ARTIFACT_DIR / f"{name}.schema.json"
    assert path.is_file(), (
        f"missing artifact {path}. Run `pnpm emit:schema`. A contract that is "
        f"not emitted is invisible across the language boundary."
    )
    return json.loads(path.read_text(encoding="utf-8"))


def validator_for(name: str) -> Draft202012Validator:
    schema = load_artifact(name)
    Draft202012Validator.check_schema(schema)
    return Draft202012Validator(schema)


def is_valid(name: str, instance: object) -> bool:
    return validator_for(name).is_valid(instance)


