class TestEveryArtifactIsEmittedAndLoadable:
    @pytest.mark.parametrize("name", EXPECTED_ARTIFACTS)
    def test_loads_as_a_draft_2020_12_schema(self, name):
        validator_for(name)  # check_schema raises on a malformed emission

    @pytest.mark.parametrize("name", EXPECTED_ARTIFACTS)
    def test_declares_the_draft_it_was_emitted_as(self, name):
        assert (
            load_artifact(name)["$schema"]
            == "https://json-schema.org/draft/2020-12/schema"
        )

    def test_no_contract_is_emitted_that_this_module_does_not_know_about(self):
        """A new contract must be added here, not silently emitted.

        The Python side is the reason these artifacts exist; a contract that
        reaches the oracle without a fixture is a contract nobody validated.
        """
        on_disk = {p.name[: -len(".schema.json")] for p in ARTIFACT_DIR.glob("*.schema.json")}
        assert on_disk == set(EXPECTED_ARTIFACTS), (
            "the emitted artifact set and EXPECTED_ARTIFACTS disagree — update "
            "this list when JSON_SCHEMA_SOURCES changes"
        )


